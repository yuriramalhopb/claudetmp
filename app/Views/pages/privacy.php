<section class="section">
    <div class="container narrow prose">
        <h2>Quais dados coletamos</h2>
        <p>Nome, apelido, e-mail, telefone, cidade, data de nascimento, dados da moto, nível de experiência, Instagram, foto de perfil e, opcionalmente, tipo sanguíneo e contato de emergência.</p>
        <h2>Para que usamos</h2>
        <p>Exclusivamente para organizar as trilhas da turma, confirmar presenças e — no caso dos dados de saúde/emergência — agir rapidamente em caso de acidente.</p>
        <h2>Quem vê seus dados</h2>
        <ul>
            <li><strong>Público:</strong> apelido/nome, cidade, moto, nível, Instagram e foto (apenas após aprovação).</li>
            <li><strong>Trilheiros logados:</strong> seu WhatsApp, somente se você autorizar.</li>
            <li><strong>Administração:</strong> todos os dados, incluindo tipo sanguíneo e contato de emergência. Cada acesso à ficha completa é registrado em log de auditoria.</li>
        </ul>
        <h2>Segurança</h2>
        <p>Senhas são armazenadas com criptografia forte (Argon2id/bcrypt), a conexão é protegida e as fotos enviadas têm os metadados de localização (GPS) removidos automaticamente.</p>
        <h2>Seus direitos</h2>
        <p>Em <a href="/minha-conta/editar">Minha conta</a> você pode corrigir seus dados, baixar uma cópia deles e excluir sua conta a qualquer momento. Dúvidas: <a href="/contato">fale conosco</a>.</p>
    </div>
</section>
